def build_cnn(seed=SEED):
    tf.keras.utils.set_random_seed(seed)
    inputs = tf.keras.Input(shape=(32, 32, 3))
    x = tf.keras.layers.Conv2D(32, 3, padding="same", activation="relu")(inputs)
    x = tf.keras.layers.MaxPooling2D()(x)
    x = tf.keras.layers.Conv2D(64, 3, padding="same", activation="relu")(x)
    x = tf.keras.layers.MaxPooling2D()(x)
    x = tf.keras.layers.Conv2D(128, 3, padding="same", activation="relu")(x)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    features = tf.keras.layers.Dense(128, activation="relu", name="features")(x)
    logits = tf.keras.layers.Dense(10, name="logits")(features)
    return tf.keras.Model(inputs, [logits, features], name="cifar10_cnn")


def train_model(augmented=False, seed=SEED, epochs=EPOCHS):

    base_model = build_cnn(seed)

    if augmented:

        # Augmentation receives raw images in [0, 1]
        inputs = tf.keras.Input(shape=(32, 32, 3))

        x = tf.keras.layers.RandomFlip("horizontal")(inputs)
        x = tf.keras.layers.RandomTranslation(0.08, 0.08)(x)
        x = tf.keras.layers.RandomRotation(0.05)(x)
        x = tf.keras.layers.RandomContrast(0.15)(x)

        # Normalize only AFTER augmentation
        x = (x - CIFAR_MEAN) / CIFAR_STD

        logits, _ = base_model(x)

        training_model = tf.keras.Model(inputs, logits)

        # IMPORTANT: Use raw datasets for augmented training
        train_data = raw_train_ds
        val_data = raw_val_ds

    else:

        # Clean model receives already normalized images
        inputs = base_model.input
        logits, _ = base_model(inputs)

        training_model = tf.keras.Model(inputs, logits)

        train_data = train_ds
        val_data = val_ds

    training_model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
        loss=tf.keras.losses.SparseCategoricalCrossentropy(
            from_logits=True
        ),
        metrics=["accuracy"]
    )

    history = training_model.fit(
        train_data,
        validation_data=val_data,
        epochs=epochs,
        verbose=1
    )

    return base_model, history


