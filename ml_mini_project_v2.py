"""## 7. Generate controlled synthetic corruptions

Corruptions are applied to raw pixel images before CIFAR normalization. Severity is 1–5. These are simple controlled transformations for this project; they are not the official CIFAR-10-C benchmark.
"""

def corrupt_batch(images, corruption, severity):
    x = tf.cast(images, tf.float32) / 255.0
    s = float(severity)

    if corruption == "gaussian_noise":
        noise = tf.random.stateless_normal(
            tf.shape(x), seed=[SEED + int(severity), 17],
            mean=0.0, stddev=0.04 * s
        )
        x = x + noise
    elif corruption == "brightness":
        x = tf.image.adjust_brightness(x, delta=0.08 * s)
    elif corruption == "contrast":
        x = tf.image.adjust_contrast(x, contrast_factor=1.0 + 0.25 * s)
    elif corruption == "blur":
        # Gaussian blur using depthwise convolution.
        sigma = 0.35 * s
        coords = tf.range(-2, 3, dtype=tf.float32)
        g = tf.exp(-(coords ** 2) / (2.0 * sigma ** 2))
        g = g / tf.reduce_sum(g)
        kernel2d = tf.tensordot(g, g, axes=0)
        kernel2d = kernel2d[:, :, tf.newaxis, tf.newaxis]
        kernel = tf.tile(kernel2d, [1, 1, 3, 1])
        x = tf.nn.depthwise_conv2d(x, kernel, strides=[1,1,1,1], padding="SAME")
    elif corruption == "grayscale":
        gray = tf.image.rgb_to_grayscale(x)
        x = tf.image.grayscale_to_rgb(gray)
    elif corruption == "rotation":
        # 90-degree rotations are discrete and reproducible.
        k = max(1, min(3, int(round(s * 3 / 5))))
        x = tf.image.rot90(x, k=k)
    else:
        raise ValueError("Unknown corruption: " + corruption)

    x = tf.clip_by_value(x, 0.0, 1.0)
    return tf.cast(tf.round(x * 255.0), tf.uint8)

