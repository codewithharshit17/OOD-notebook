def evaluate_model_on_conditions(
    model,
    model_name,
    means,
    precision
):

    rows = []

    print(f"\nEvaluating: {model_name}")

    # Clean CIFAR-10 ID scores
    id_scores, _, _ = get_model_scores(
        model,
        x_test_eval,
        means,
        precision
    )

    # Semantic OOD: SVHN
    ood_scores, _, _ = get_model_scores(
        model,
        x_svhn_eval,
        means,
        precision
    )

    # --------------------------------------------------------
    # Semantic OOD comparison
    # --------------------------------------------------------

    for method in id_scores:

        metrics = calculate_ood_metrics(
            id_scores[method],
            ood_scores[method]
        )

        rows.append({
            "Model": model_name,
            "Shift_Type": "Semantic OOD",
            "Condition": "SVHN",
            "Method": method,
            **metrics
        })

    # --------------------------------------------------------
    # Covariate shift experiments
    # --------------------------------------------------------

    corruption_types = [
        "gaussian_noise",
        "blur",
        "brightness"
    ]

    severities = [1, 3, 5]

    for corr in corruption_types:

        for sev in severities:

            print(
                f"Evaluating {corr}, severity {sev}..."
            )

            # Generate corrupted CIFAR-10 images
            x_corr = corrupt_batch(
                x_test_eval,
                corr,
                sev
            )

            # Get corrupted image scores
            corr_scores, corr_logits, _ = get_model_scores(
                model,
                x_corr,
                means,
                precision
            )

            # Classification accuracy on corrupted images
            corr_acc = np.mean(
                np.argmax(corr_logits, axis=1)
                == y_test_eval
            )

            # Compare clean ID against corrupted ID
            for method in id_scores:

                metrics = calculate_ood_metrics(
                    id_scores[method],
                    corr_scores[method]
                )

                rows.append({
                    "Model": model_name,
                    "Shift_Type": "Covariate Shift",
                    "Condition": f"{corr}_severity_{sev}",
                    "Method": method,
                    "Corrupted_ID_accuracy": corr_acc,
                    **metrics
                })

    return rows


