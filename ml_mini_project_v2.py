def mahalanobis_ood(features):
    # Return minimum squared Mahalanobis distance to any class mean.
    distances = []
    for mean in class_means:
        delta = features - mean
        d = np.einsum("bi,ij,bj->b", delta, precision, delta)
        distances.append(d)
    return np.min(np.stack(distances, axis=1), axis=1)

def get_all_scores(model, images):
    logits, features = predict_arrays(model, images)
    result = scores_from_logits(logits)
    result["Mahalanobis"] = mahalanobis_ood(features)
    return result, logits, features


def fit_mahalanobis_statistics(model, images, labels):

    _, features = predict_arrays(model, images)

    labels = labels[:len(features)]

    means = []

    for c in range(10):
        class_features = features[labels == c]
        means.append(np.mean(class_features, axis=0))

    means = np.stack(means)

    centered = np.concatenate([
        features[labels == c] - means[c]
        for c in range(10)
    ], axis=0)

    covariance = LedoitWolf().fit(centered)

    return means, covariance.precision_


def get_model_scores(model, images, means, precision):

    logits, features = predict_arrays(model, images)

    result = scores_from_logits(logits)

    distances = []

    for mean in means:
        delta = features - mean
        d = np.einsum(
            "bi,ij,bj->b",
            delta, precision, delta
        )
        distances.append(d)

    result["Mahalanobis"] = np.min(
        np.stack(distances, axis=1),
        axis=1
    )

    return result, logits, features

# 9. Evaluation metrics: ID scores first, OOD scores second.
# FPR95 = fraction of OOD examples incorrectly accepted as ID
# when 95% of ID examples are accepted.

def calculate_ood_metrics(id_scores, ood_scores):

    id_scores = np.asarray(id_scores)
    ood_scores = np.asarray(ood_scores)

    y_true = np.concatenate([
        np.zeros(len(id_scores)),
        np.ones(len(ood_scores))
    ])

    scores = np.concatenate([
        id_scores,
        ood_scores
    ])

    auroc = roc_auc_score(y_true, scores)
    aupr = average_precision_score(y_true, scores)

    # Standard FPR95:
    # Choose threshold that detects 95% of OOD samples.
    threshold_ood95 = np.quantile(ood_scores, 0.05)

    fpr95 = np.mean(id_scores >= threshold_ood95)

    # Also retain the complementary operating point:
    # 95% of ID samples are accepted.
    threshold_id95 = np.quantile(id_scores, 0.95)

    ood_miss_at_id95 = np.mean(
        ood_scores <= threshold_id95
    )

    return {
        "AUROC": auroc,
        "AUPR": aupr,
        "FPR95": fpr95,
        "OOD_miss_at_ID95": ood_miss_at_id95,
        "ID95_threshold": threshold_id95
    }


