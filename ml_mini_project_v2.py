"""## 8. OOD scoring methods

All scores are oriented so that **larger means more OOD-like**:
- MSP score = negative maximum softmax probability.
- Energy score = negative temperature-scaled log-sum-exp of logits.
- Entropy score = predictive entropy.
- Mahalanobis score = minimum class-conditional feature distance (larger distance means more OOD-like).
"""

def scores_from_logits(logits, temperature=1.0):
    z = logits / temperature
    probs = tf.nn.softmax(z, axis=1).numpy()
    msp_ood = -np.max(probs, axis=1)
    energy_ood = -temperature * tf.reduce_logsumexp(z, axis=1).numpy()
    entropy_ood = -np.sum(probs * np.log(np.clip(probs, 1e-12, 1.0)), axis=1)
    return {
        "MSP": msp_ood,
        "Energy": energy_ood,
        "Entropy": entropy_ood
    }

